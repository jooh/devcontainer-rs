    #[test]
    fn discover_feature_test_cases_applies_skip_and_feature_filters() {
        let root = crate::test_support::unique_temp_dir("feature-test-discovery");
        let feature = root.join("test").join("demo");
        let global = root.join("test").join("_global");
        fs::create_dir_all(&feature).expect("feature test dir");
        fs::create_dir_all(&global).expect("global test dir");
        fs::write(feature.join("test.sh"), "#!/bin/sh\n").expect("test script");
        fs::write(feature.join("duplicate.sh"), "#!/bin/sh\n").expect("duplicate script");
        fs::write(feature.join("custom.sh"), "#!/bin/sh\n").expect("scenario script");
        fs::write(
            feature.join("scenarios.json"),
            r#"{
  "custom": {
    "image": "ubuntu:latest"
  }
}"#,
        )
        .expect("scenarios");
        fs::write(global.join("global.sh"), "#!/bin/sh\n").expect("global script");
        fs::write(
            global.join("scenarios.json"),
            r#"{
  "global": {
    "image": "ubuntu:latest"
  }
}"#,
        )
        .expect("global scenarios");

        let skip_scenarios = discover_feature_test_cases(&[
            "--skip-scenarios".to_string(),
            root.display().to_string(),
        ])
        .expect("skip scenarios");
        assert_eq!(
            skip_scenarios
                .iter()
                .map(|case| case.name.as_str())
                .collect::<Vec<_>>(),
            vec!["demo", "demo executed twice with randomized options"]
        );

        let feature_filtered = discover_feature_test_cases(&[
            "--features".to_string(),
            "other".to_string(),
            root.display().to_string(),
        ])
        .expect("feature filtered");
        assert!(feature_filtered.is_empty());

        let skip_generated = discover_feature_test_cases(&[
            "--skip-autogenerated".to_string(),
            "--skip-duplicated".to_string(),
            root.display().to_string(),
        ])
        .expect("skip generated");
        assert_eq!(
            skip_generated
                .iter()
                .map(|case| case.name.as_str())
                .collect::<Vec<_>>(),
            vec!["custom", "global"]
        );
        let _ = fs::remove_dir_all(root);
    }


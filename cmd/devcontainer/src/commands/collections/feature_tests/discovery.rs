    #[test]
    fn prepare_duplicate_feature_case_materializes_two_installations_and_exec_env() {
        let root = crate::test_support::unique_temp_dir("feature-test-discovery");
        let workspace = crate::test_support::unique_temp_dir("feature-test-discovery-workspace");
        let feature_dir = root.join("src").join("demo");
        let test_dir = root.join("test").join("demo");
        fs::create_dir_all(&feature_dir).expect("feature dir");
        fs::create_dir_all(&test_dir).expect("test dir");
        fs::write(
            feature_dir.join("devcontainer-feature.json"),
            r#"{
  "id": "demo",
  "version": "1.0.0",
  "options": {
    "color": {
      "type": "string",
      "enum": ["blue", "green"],
      "default": "blue"
    }
  }
}"#,
        )
        .expect("manifest");
        fs::write(test_dir.join("duplicate.sh"), "#!/bin/sh\n").expect("script");
        let case = FeatureTestCase {
            name: "demo duplicate".to_string(),
            script_path: test_dir.join("duplicate.sh"),
            execution: FeatureTestExecution::Duplicate {
                feature: "demo".to_string(),
            },
        };

        let prepared = prepare_feature_test_case_in_workspace(
            &test_options(root.clone()),
            &case,
            workspace.clone(),
        )
        .expect("prepare duplicate case");

        assert_eq!(prepared.script_name, "duplicate.sh");
        assert_eq!(
            prepared.base_image,
            BaseImageSource::Image("debian:bookworm-slim".to_string())
        );
        assert_eq!(prepared.feature_installations.len(), 2);
        assert_eq!(
            prepared.feature_installations[0].source,
            FeatureInstallationSource::Local(feature_dir.clone())
        );
        assert_eq!(
            prepared.feature_installations[1].source,
            FeatureInstallationSource::Local(feature_dir)
        );
        assert!(prepared
            .exec_env
            .iter()
            .any(|(key, value)| key == "COLOR" && value == "green"));
        assert!(prepared
            .exec_env
            .iter()
            .any(|(key, value)| key == "COLOR__DEFAULT" && value == "blue"));
        let _ = fs::remove_dir_all(root);
        let _ = fs::remove_dir_all(workspace);
    }

